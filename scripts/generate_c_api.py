"""Generate language-independent C ABI dispatch and token grants from public C++ headers."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
output = root / 'src/detail'
services = [('room_service_client', 'Room'), ('egress_client', 'Egress'),
            ('ingress_client', 'Ingress'), ('sip_client', 'Sip'),
            ('agent_dispatch_client', 'AgentDispatch'), ('connector_client', 'Connector')]
dispatch = ['// Generated by scripts/generate_c_api.py; shared by all bindings.']
for header, accessor in services:
    source = (root / f'include/livekit/server/{header}.h').read_text(encoding='utf-8')
    methods = re.findall(r'\[\[nodiscard\]\]\s+model::(\w+)\s+(\w+)\(const model::(\w+)& request\) const;', source)
    for _, method, request in methods:
        dispatch += [f'if (operation == "{accessor}.{method}") {{',
                     '\treturn std::string(',
                     f'\t    api.{accessor}().{method}(model::{request}(request))',
                     '\t        .Json());', '}']

source = (root / 'include/livekit/server/access_token.h').read_text(encoding='utf-8')
grants = ['// Generated by scripts/generate_c_api.py; shared by all bindings.']
for cls, setter, name in [('VideoGrant', 'SetVideoGrant', 'video'),
                          ('SipGrant', 'SetSipGrant', 'sip'),
                          ('AgentGrant', 'SetAgentGrant', 'agent')]:
    body = re.search(r'struct ' + cls + r' \{(.*?)\n\};', source, re.S)[1]
    grants += [f'if (Has(options, "{name}")) {{',
               f'\tconst auto& fields = Object(options, "{name}");', f'\t{cls} grant;']
    for typ, field in re.findall(r'([\w:<>]+) (\w+)(?:\{\})?;', body):
        if typ == 'std::optional<bool>':
            grants += [f'\tif (Has(fields, "{field}")) {{',
                       f'\t\tgrant.{field} = Boolean(fields, "{field}");', '\t}']
        else:
            function = {'bool': 'Boolean', 'std::string': 'String',
                        'std::vector<std::string>': 'StringList'}[typ]
            grants += [f'\tgrant.{field} = {function}(fields, "{field}");']
    grants += [f'\ttoken.{setter}(std::move(grant));', '}']

for name, lines in [('dispatch.inc', dispatch), ('grants.inc', grants)]:
    (output / name).write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
