"""Generate .NET model wrappers, server methods, and token grants from public C++ headers."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[3]
output = root / 'pkg/dotnet/src/LiveKit.Server.Cpp'
banner = '// Generated by pkg/dotnet/scripts/generate_api.py.\n#nullable enable\n'


def write(name, lines):
    (output / name).write_text(banner + '\n'.join(lines).rstrip() + '\n', encoding='utf-8', newline='\n')


def pascal(name):
    return ''.join(part[:1].upper() + part[1:] for part in name.split('_'))


names = re.findall(r'^LIVEKIT_SERVER_DECLARE_MODEL\((\w+)\)',
                   (root / 'include/livekit/server/model/models.h').read_text(encoding='utf-8'), re.M)
models = ['namespace LiveKit.Server.Models;', '']
for name in names:
    models += [f'public sealed class {name} : ProtocolModel', '{',
               f'    public {name}() : base("{{}}") {{ }}',
               f'    public {name}(string json) : base(json) {{ }}',
               f'    public {name}(object fields) : base(fields) {{ }}',
               f'    public static {name} FromJson(string json) => new(json);', '}', '']
write('Models.g.cs', models)
services = ['namespace LiveKit.Server;', '']
count = 0
for cls, header, accessor in [('RoomServiceClient', 'room_service_client', 'Room'),
                              ('EgressClient', 'egress_client', 'Egress'),
                              ('IngressClient', 'ingress_client', 'Ingress'),
                              ('SipClient', 'sip_client', 'Sip'),
                              ('AgentDispatchClient', 'agent_dispatch_client', 'AgentDispatch'),
                              ('ConnectorClient', 'connector_client', 'Connector')]:
    source = (root / f'include/livekit/server/{header}.h').read_text(encoding='utf-8')
    methods = re.findall(r'\[\[nodiscard\]\]\s+model::(\w+)\s+(\w+)\(const model::(\w+)& request\) const;', source)
    services += [f'public sealed class {cls}', '{', '    private readonly LiveKitApi _api;',
                 f'    internal {cls}(LiveKitApi api) => _api = api;', '']
    for result, method, request in methods:
        optional = '? request = null' if method == 'ListRooms' else ' request'
        argument = 'request ?? new()' if method == 'ListRooms' else 'request'
        services += [f'    public Models.{result} {method}(Models.{request}{optional}) =>',
                     f'        new(_api.Call("{accessor}.{method}", {argument}));', '']
        count += 1
    if accessor == 'AgentDispatch':
        services += ['    public Models.AgentDispatch? GetDispatch(string dispatchId, string room) =>',
                     '        _api.GetDispatch(dispatchId, room);', '']
    services += ['}', '']
write('Services.g.cs', services)

grants = ['namespace LiveKit.Server;', '']
source = (root / 'include/livekit/server/access_token.h').read_text(encoding='utf-8')
for cls in ('VideoGrant', 'SipGrant', 'AgentGrant'):
    body = re.search(r'struct ' + cls + r' \{(.*?)\n\};', source, re.S)[1]
    fields = re.findall(r'([\w:<>]+) (\w+)(?:\{\})?;', body)
    grants += [f'public sealed class {cls}', '{']
    for typ, field in fields:
        name = pascal(field)
        if typ in ('bool', 'std::optional<bool>'):
            annotation = 'bool?' if typ.startswith('std::optional') else 'bool'
            grants += [f'    public {annotation} {name} {{ get; init; }}']
        elif typ == 'std::string':
            grants += [f'    private string _{field} = "";',
                       f'    public string {name}', '    {', f'        get => _{field};',
                       f'        init => _{field} = value ?? throw new ArgumentNullException(nameof({name}));', '    }']
        else:
            grants += [f'    private IReadOnlyList<string> _{field} = Array.Empty<string>();',
                       f'    public IReadOnlyList<string> {name}', '    {', f'        get => _{field};',
                       '        init', '        {', '            ArgumentNullException.ThrowIfNull(value);',
                       '            var items = value.ToArray();',
                       '            if (items.Any(item => item is null)) throw new ArgumentException("sources must contain strings");',
                       f'            _{field} = Array.AsReadOnly(items);', '        }', '    }']
    grants += ['', '    internal Dictionary<string, object?> ToFields()', '    {',
               '        var fields = new Dictionary<string, object?>', '        {']
    for typ, field in fields:
        if not typ.startswith('std::optional'):
            grants += [f'            ["{field}"] = {pascal(field)},']
    grants += ['        };']
    for typ, field in fields:
        if typ.startswith('std::optional'):
            grants += [f'        if ({pascal(field)} is not null) fields["{field}"] = {pascal(field)};']
    grants += ['        return fields;', '    }', '}', '']
write('Grants.g.cs', grants)
print(f'Generated {len(names)} .NET models and {count} service methods')
