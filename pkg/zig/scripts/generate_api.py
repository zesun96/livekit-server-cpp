"""Generate Zig typed JSON models, service methods and grants from the public C++ headers."""
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parents[3]
output = root / 'pkg/zig/src'


def write(name, lines):
    path = output / name
    path.write_text('// Generated by pkg/zig/scripts/generate_api.py.\n' + '\n'.join(lines).rstrip() + '\n',
                    encoding='utf-8', newline='\n')
    subprocess.run(['zig', 'fmt', str(path)], check=True, capture_output=True)


names = re.findall(r'^LIVEKIT_SERVER_DECLARE_MODEL\((\w+)\)',
                   (root / 'include/livekit/server/model/models.h').read_text(encoding='utf-8'), re.M)
models = ['const Model = @import("model.zig").Model;']
models += [f'pub const {name} = Model("{name}");' for name in names]
models += ['test "all 86 model types own JSON snapshots" {', '    const std = @import("std");',
           '    const a = std.testing.allocator;', '    inline for (.{ ' + ', '.join(names) + ' }) |M| {',
           '        var model = try M.fromValue(a, .{ .name = "中文😀\\x00", .large = "9007199254740993" });',
           '        defer model.deinit();', '        var value = try model.toValue(a);', '        defer value.deinit();',
           '        try std.testing.expectEqualStrings("9007199254740993", value.value.object.get("large").?.string);',
           '        var empty = try M.empty(a);', '        defer empty.deinit();',
           '        try std.testing.expectEqualStrings("{}", empty.json);', '    }', '}']
write('models.zig', models)

services = ['const Allocator = @import("std").mem.Allocator;', 'const LiveKitApi = @import("api.zig").LiveKitApi;',
            'const models = @import("models.zig");', 'const Result = @import("result.zig").Result;']
count = 0
for cls, header, accessor in [('RoomServiceClient', 'room_service_client', 'Room'),
                              ('EgressClient', 'egress_client', 'Egress'),
                              ('IngressClient', 'ingress_client', 'Ingress'),
                              ('SipClient', 'sip_client', 'Sip'),
                              ('AgentDispatchClient', 'agent_dispatch_client', 'AgentDispatch'),
                              ('ConnectorClient', 'connector_client', 'Connector')]:
    source = (root / f'include/livekit/server/{header}.h').read_text(encoding='utf-8')
    methods = re.findall(r'\[\[nodiscard\]\]\s+model::(\w+)\s+(\w+)\(const model::(\w+)& request\) const;', source)
    services += [f'pub const {cls} = struct {{', '    api: *const LiveKitApi,']
    for result, method, request in methods:
        services += [f'    pub fn {method[0].lower() + method[1:]}(self: @This(), allocator: Allocator, request: models.{request}) !Result(models.{result}) {{',
                     f'        return self.api.call(allocator, models.{result}, "{accessor}.{method}", request.json);', '    }']
        count += 1
    if accessor == 'AgentDispatch':
        services += ['    pub fn getDispatch(self: @This(), allocator: Allocator, dispatch_id: []const u8, room: []const u8) !Result(?models.AgentDispatch) {',
                     '        return self.api.lookupDispatch(allocator, dispatch_id, room);', '    }']
    services += ['};']
write('services.zig', services)

grants = []
source = (root / 'include/livekit/server/access_token.h').read_text(encoding='utf-8')
for cls in ('VideoGrant', 'SipGrant', 'AgentGrant'):
    body = re.search(r'struct ' + cls + r' \{(.*?)\n\};', source, re.S)[1]
    grants += [f'pub const {cls} = struct {{']
    for typ, name in re.findall(r'([\w:<>]+) (\w+)(?:\{\})?;', body):
        annotation, default = {'bool': ('bool', 'false'), 'std::string': ('[]const u8', '""'),
                               'std::optional<bool>': ('?bool', 'null'),
                               'std::vector<std::string>': ('[]const []const u8', '&.{}')}[typ]
        grants += [f'    {name}: {annotation} = {default},']
    grants += ['};']
write('grants.zig', grants)
assert len(names) == 86 and count == 52
print(f'Generated {len(names)} Zig models and {count} service methods')
