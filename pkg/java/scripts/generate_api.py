"""Regenerate JSON model wrappers, service methods, and JNI dispatch from public C++ headers."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[3]
binding = root / 'pkg/java'
java = binding / 'src/main/java/io/livekit/server'
java.mkdir(parents=True, exist_ok=True)


def write(path, source):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding='utf-8', newline='\n')


models = re.findall(r'^LIVEKIT_SERVER_DECLARE_MODEL\((\w+)\)',
                    (root / 'include/livekit/server/model/models.h').read_text(), re.M)
source = ['package io.livekit.server;\n',
          '/** SDK-owned protobuf JSON models, matching the C++ public model API. */',
          'public final class Models {', '    private Models() {}']
for name in models:
    source += [f'    public static final class {name} extends ProtocolModel {{',
               f'        public {name}() {{ super("{{}}"); }}',
               f'        public {name}(String json) {{ super(json); }}',
               f'        public static {name} fromJson(String json) {{ return new {name}(json); }}',
               '    }']
source += ['}']
write(java / 'Models.java', '\n'.join(source) + '\n')
dispatch = ['// Generated by scripts/generate_api.py; do not edit.']
services = [('RoomServiceClient', 'room_service_client', 'Room'),
            ('EgressClient', 'egress_client', 'Egress'),
            ('IngressClient', 'ingress_client', 'Ingress'),
            ('SipClient', 'sip_client', 'Sip'),
            ('AgentDispatchClient', 'agent_dispatch_client', 'AgentDispatch'),
            ('ConnectorClient', 'connector_client', 'Connector')]
count = 0
for cls, header, accessor in services:
    text = (root / f'include/livekit/server/{header}.h').read_text()
    methods = re.findall(r'\[\[nodiscard\]\]\s+model::(\w+)\s+(\w+)\(const model::(\w+)& request\) const;', text)
    source = ['package io.livekit.server;\n', 'import static io.livekit.server.Models.*;\n',
              f'public final class {cls} {{', '    private final LiveKitApi api;',
              f'    {cls}(LiveKitApi api) {{ this.api = api; }}']
    for result, method, request in methods:
        lower = method[0].lower() + method[1:]
        op = f'{accessor}.{method}'
        source += [f'    public {result} {lower}({request} request) {{',
                   f'        return new {result}(api.call("{op}", request));', '    }']
        dispatch += [f'if (operation == "{op}") {{',
                     f'\treturn std::string(api.{accessor}().{method}(model::{request}(request)).Json());', '}']
        count += 1
    if accessor == 'Room':
        source += ['    public ListRoomsResponse listRooms() { return listRooms(new ListRoomsRequest()); }']
    if accessor == 'AgentDispatch':
        source += ['    /** Returns null when the dispatch does not exist. */',
                   '    public AgentDispatch getDispatch(String dispatchId, String room) {',
                   '        String json = api.getDispatch(dispatchId, room);',
                   '        return json == null ? null : new AgentDispatch(json);', '    }']
    source += ['}']
    write(java / f'{cls}.java', '\n'.join(source) + '\n')
write(binding / 'src/main/cpp/dispatch.inc', '\n'.join(dispatch) + '\n')
print(f'Generated {len(models)} models and {count} service methods')

token_header = (root / 'include/livekit/server/access_token.h').read_text()
for cls in ('VideoGrant', 'SipGrant', 'AgentGrant'):
    body = re.search(r'struct ' + cls + r' \{(.*?)\n\};', token_header, re.S)[1]
    source = ['package io.livekit.server;\n',
              '/** Mutable token grant builder. Null optional booleans retain server defaults. */',
              f'public final class {cls} {{']
    entries = []
    for typ, field in re.findall(r'([\w:<>]+) (\w+)(?:\{\})?;', body):
        name = re.sub(r'_([a-z])', lambda m: m[1].upper(), field)
        jtype, default = {'bool': ('boolean', 'false'), 'std::string': ('String', '""'),
                          'std::optional<bool>': ('Boolean', 'null'),
                          'std::vector<std::string>': ('java.util.List<String>', 'java.util.List.of()')}[typ]
        source += [f'    public {jtype} {name} = {default};']
        entries += [f'        if ({name} != null) fields.put("{name}", {name});' if jtype == 'Boolean'
                    else f'        fields.put("{name}", java.util.List.copyOf({name}));' if typ.startswith('std::vector')
                    else f'        fields.put("{name}", java.util.Objects.requireNonNull({name}, "{name}"));' if jtype == 'String'
                    else f'        fields.put("{name}", {name});']
    source += ['    java.util.Map<String, Object> fields() {',
               '        var fields = new java.util.LinkedHashMap<String, Object>();',
               *entries, '        return fields;', '    }', '}']
    write(java / f'{cls}.java', '\n'.join(source) + '\n')
