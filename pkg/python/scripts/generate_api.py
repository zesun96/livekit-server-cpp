"""Regenerate Python protocol models, server services, and grants from public C++ headers."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[3]
output = root / 'pkg/python/src/livekit_server'


def write(name, lines):
    (output / name).write_text('\n'.join(lines).rstrip() + '\n', encoding='utf-8', newline='\n')


def snake(name):
    name = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).lower()


names = re.findall(r'^LIVEKIT_SERVER_DECLARE_MODEL\((\w+)\)',
                   (root / 'include/livekit/server/model/models.h').read_text(encoding='utf-8'), re.M)
models = ['# Generated by pkg/python/scripts/generate_api.py.', 'from ._model import ProtocolModel', '']
for name in names:
    models += ['', f'class {name}(ProtocolModel):', '    __slots__ = ()']
models += ['', f'__all__ = {names!r}']
write('models.py', models)

services = ['# Generated by pkg/python/scripts/generate_api.py.', 'from __future__ import annotations',
            'from typing import TYPE_CHECKING', 'from . import models', '',
            'if TYPE_CHECKING:', '    from .api import LiveKitApi', '', '',
            'class _Service:', '    def __init__(self, api: LiveKitApi):', '        self._api = api']
count = 0
for cls, header, accessor in [('RoomServiceClient', 'room_service_client', 'Room'),
                              ('EgressClient', 'egress_client', 'Egress'),
                              ('IngressClient', 'ingress_client', 'Ingress'),
                              ('SipClient', 'sip_client', 'Sip'),
                              ('AgentDispatchClient', 'agent_dispatch_client', 'AgentDispatch'),
                              ('ConnectorClient', 'connector_client', 'Connector')]:
    source = (root / f'include/livekit/server/{header}.h').read_text(encoding='utf-8')
    methods = re.findall(r'\[\[nodiscard\]\]\s+model::(\w+)\s+(\w+)\(const model::(\w+)& request\) const;', source)
    services += ['', '', f'class {cls}(_Service):']
    for result, method, request in methods:
        default = ' | None = None' if method == 'ListRooms' else ''
        services += [f'    def {snake(method)}(self, request: models.{request}{default}) -> models.{result}:']
        if default:
            services += ['        if request is None:', f'            request = models.{request}()']
        services += [f'        return self._api._call("{accessor}.{method}", request,',
                     f'                               models.{request}, models.{result})', '']
        count += 1
    if accessor == 'AgentDispatch':
        services += ['    def get_dispatch(self, dispatch_id: str, room: str) -> models.AgentDispatch | None:',
                     '        return self._api._get_dispatch(dispatch_id, room)']
write('services.py', services)

grants = ['# Generated by pkg/python/scripts/generate_api.py.', 'from __future__ import annotations',
          'from dataclasses import dataclass, field', 'from ._model import Grant']
source = (root / 'include/livekit/server/access_token.h').read_text(encoding='utf-8')
for cls in ('VideoGrant', 'SipGrant', 'AgentGrant'):
    body = re.search(r'struct ' + cls + r' \{(.*?)\n\};', source, re.S)[1]
    grants += ['', '', '@dataclass(frozen=True, slots=True)', f'class {cls}(Grant):']
    for typ, name in re.findall(r'([\w:<>]+) (\w+)(?:\{\})?;', body):
        annotation, default, kind = {'bool': ('bool', 'False', 'boolean'),
                                    'std::string': ('str', '""', 'string'),
                                    'std::optional<bool>': ('bool | None', 'None', 'optional_boolean'),
                                    'std::vector<std::string>': ('tuple[str, ...]', '()', 'strings')}[typ]
        grants += [f'    {name}: {annotation} = field(default={default}, metadata={{"kind": "{kind}"}})']
write('grants.py', grants)
print(f'Generated {len(names)} Python models and {count} service methods')
