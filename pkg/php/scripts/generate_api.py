"""Generate PHP model wrappers, service methods and grants from public C++ headers."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[3]
output = root / 'pkg/php/src'
banner = '<?php\ndeclare(strict_types=1);\n\n// Generated by pkg/php/scripts/generate_api.py.\n'


def write(name, lines):
    (output / name).write_text(banner + '\n'.join(lines).rstrip() + '\n', encoding='utf-8', newline='\n')


def camel(name):
    parts = name.split('_')
    return parts[0] + ''.join(p.title() for p in parts[1:])


def model_name(name):
    # Empty is a PHP keyword, including in namespaced class declarations.
    return 'EmptyMessage' if name == 'Empty' else name


names = re.findall(r'^LIVEKIT_SERVER_DECLARE_MODEL\((\w+)\)',
                   (root / 'include/livekit/server/model/models.h').read_text(encoding='utf-8'), re.M)
models = ['namespace LiveKit\\Server\\Models;', '', 'use LiveKit\\Server\\ProtocolModel;', '']
for name in names:
    models += [f'final readonly class {model_name(name)} extends ProtocolModel {{}}', '']
write('Models.php', models)

services = ['namespace LiveKit\\Server;', '']
count = 0
for cls, header, accessor in [('RoomServiceClient', 'room_service_client', 'Room'),
                              ('EgressClient', 'egress_client', 'Egress'),
                              ('IngressClient', 'ingress_client', 'Ingress'),
                              ('SipClient', 'sip_client', 'Sip'),
                              ('AgentDispatchClient', 'agent_dispatch_client', 'AgentDispatch'),
                              ('ConnectorClient', 'connector_client', 'Connector')]:
    source = (root / f'include/livekit/server/{header}.h').read_text(encoding='utf-8')
    methods = re.findall(r'\[\[nodiscard\]\]\s+model::(\w+)\s+(\w+)\(const model::(\w+)& request\) const;', source)
    services += [f'final readonly class {cls}', '{',
                 '    public function __construct(private LiveKitApi $api) {}', '']
    for result, method, request in methods:
        result, request = model_name(result), model_name(request)
        signature = f'Models\\{request} $request'
        argument = '$request'
        if method == 'ListRooms':
            signature = f'?Models\\{request} $request = null'
            argument += f' ?? new Models\\{request}()'
        services += [f'    public function {method[0].lower() + method[1:]}({signature}): Models\\{result}',
                     '    {', f'        return new Models\\{result}($this->api->call("{accessor}.{method}", {argument}));',
                     '    }', '']
        count += 1
    if accessor == 'AgentDispatch':
        services += ['    public function getDispatch(string $dispatchId, string $room): ?Models\\AgentDispatch',
                     '    {', '        return $this->api->getDispatch($dispatchId, $room);', '    }', '']
    services += ['}', '']
write('Services.php', services)

grants = ['namespace LiveKit\\Server;', '']
source = (root / 'include/livekit/server/access_token.h').read_text(encoding='utf-8')
for cls in ('VideoGrant', 'SipGrant', 'AgentGrant'):
    body = re.search(r'struct ' + cls + r' \{(.*?)\n\};', source, re.S)[1]
    fields = re.findall(r'([\w:<>]+) (\w+)(?:\{\})?;', body)
    grants += [f'final readonly class {cls}', '{']
    for typ, field in fields:
        if typ == 'std::vector<std::string>':
            grants += [f'    public array ${camel(field)};', '']
    grants += ['    public function __construct(']
    for typ, field in fields:
        annotation, default = {'bool': ('bool', 'false'), 'std::optional<bool>': ('?bool', 'null'),
                               'std::string': ('string', "''"), 'std::vector<std::string>': ('array', '[]')}[typ]
        visibility = '' if typ == 'std::vector<std::string>' else 'public '
        grants += [f'        {visibility}{annotation} ${camel(field)} = {default},']
    grants += ['    ) {']
    for typ, field in fields:
        if typ == 'std::vector<std::string>':
            name = '$' + camel(field)
            grants += [f'        if (!array_is_list({name})) {{',
                       "            throw new \\InvalidArgumentException('Publish sources must be a list of strings');", '        }',
                       f'        foreach ({name} as $source) {{', '            if (!is_string($source)) {',
                       "                throw new \\InvalidArgumentException('Publish sources must be strings');",
                       '            }', '        }',
                       f'        $this->{camel(field)} = array_map(static fn (string $value): string => $value, {name});']
    grants += ['    }', '', '    public function toFields(): array', '    {', '        return array_filter([']
    grants += [f"            '{field}' => $this->{camel(field)}," for _, field in fields]
    grants += ['        ], static fn ($value) => $value !== null);', '    }', '}', '']
write('Grants.php', grants)
assert len(names) == 86 and count == 52
print(f'Generated {len(names)} PHP models and {count} service methods')
