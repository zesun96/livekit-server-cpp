"""Generate Ruby models/services and native dispatch from the public C++ headers."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[3]
binding = root / 'pkg/ruby'


def write(name, source):
    path = binding / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding='utf-8', newline='\n')


def snake(name):
    return re.sub(r'(?<=[a-z0-9])(?=[A-Z])', '_', name).lower()


names = re.findall(r'^LIVEKIT_SERVER_DECLARE_MODEL\((\w+)\)',
                   (root / 'include/livekit/server/model/models.h').read_text(), re.M)
ruby = ['# frozen_string_literal: true', '# Generated by scripts/generate_api.py.',
        'module LiveKit', '  module Server', '    module Models']
ruby += [f'      class {name} < ProtocolModel; end' for name in names]
ruby += ['    end']
dispatch = ['// Generated by scripts/generate_api.py.']
services = [('RoomServiceClient', 'room_service_client', 'Room'),
            ('EgressClient', 'egress_client', 'Egress'),
            ('IngressClient', 'ingress_client', 'Ingress'),
            ('SipClient', 'sip_client', 'Sip'),
            ('AgentDispatchClient', 'agent_dispatch_client', 'AgentDispatch'),
            ('ConnectorClient', 'connector_client', 'Connector')]
count = 0
for cls, header, accessor in services:
    text = (root / f'include/livekit/server/{header}.h').read_text()
    methods = re.findall(r'\[\[nodiscard\]\]\s+model::(\w+)\s+(\w+)\(const model::(\w+)& request\) const;', text)
    ruby += [f'    class {cls}', '      def initialize(api)', '        @api = api', '      end']
    for result, method, request in methods:
        default = f' = Models::{request}.new' if method == 'ListRooms' else ''
        ruby += [f'      def {snake(method)}(request{default})',
                 f'        raise ArgumentError, "expected Models::{request}" unless request.is_a?(Models::{request})',
                 f'        Models::{result}.new(@api.call("{accessor}.{method}", request.json))', '      end']
        dispatch += [f'if (operation == "{accessor}.{method}") {{',
                     '\treturn std::string(',
                     f'\t    api.{accessor}().{method}(model::{request}(request))',
                     '\t        .Json());', '}']
        count += 1
    if accessor == 'AgentDispatch':
        ruby += ['      def get_dispatch(dispatch_id, room)',
                 '        json = @api.get_dispatch(dispatch_id, room)',
                 '        json.nil? ? nil : Models::AgentDispatch.new(json)', '      end']
    ruby += ['    end']
ruby += ['  end', 'end']
write('lib/livekit/server/generated.rb', '\n'.join(ruby) + '\n')
write('src/dispatch.inc', '\n'.join(dispatch) + '\n')

header = (root / 'include/livekit/server/access_token.h').read_text()
native = ['// Generated by scripts/generate_api.py.']
ruby = ['# frozen_string_literal: true', '# Generated by scripts/generate_api.py.',
        'module LiveKit', '  module Server']
for cls, setter in [('VideoGrant', 'SetVideoGrant'), ('SipGrant', 'SetSipGrant'), ('AgentGrant', 'SetAgentGrant')]:
    body = re.search(r'struct ' + cls + r' \{(.*?)\n\};', header, re.S)[1]
    fields = re.findall(r'([\w:<>]+) (\w+)(?:\{\})?;', body)
    ruby += [f'    class {cls} < Grant', '      FIELDS = {']
    native += [f'if (Has(options, "{snake(cls).replace("_grant", "")}")) {{',
               f'\tconst auto& fields = Object(options, "{snake(cls).replace("_grant", "")}");', f'\t{cls} grant;']
    for typ, field in fields:
        ruby += [f'        {field}: :{ {"bool": "boolean", "std::string": "string", "std::optional<bool>": "optional_boolean", "std::vector<std::string>": "strings"}[typ]},']
        if typ == 'std::optional<bool>':
            native += [f'\tif (Has(fields, "{field}")) {{',
                       f'\t\tgrant.{field} = Boolean(fields, "{field}");', '\t}']
        else:
            func = {'bool': 'Boolean', 'std::string': 'String', 'std::vector<std::string>': 'StringList'}[typ]
            native += [f'\tgrant.{field} = {func}(fields, "{field}");']
    native += [f'\ttoken.{setter}(std::move(grant));', '}']
    ruby += ['      }.freeze', '    end']
ruby += ['  end', 'end']
write('src/grants.inc', '\n'.join(native) + '\n')
write('lib/livekit/server/grants.rb', '\n'.join(ruby) + '\n')
print(f'Generated {len(names)} Ruby models and {count} service methods')
