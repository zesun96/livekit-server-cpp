"""Generate Rust JSON model wrappers, service methods and grants from public C++ headers."""
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parents[3]
output = root / 'pkg/rust/src'


def write(name, lines):
    path = output / name
    path.write_text('// Generated by pkg/rust/scripts/generate_api.py.\n' + '\n'.join(lines).rstrip() + '\n',
                    encoding='utf-8', newline='\n')
    subprocess.run(['rustfmt', '--edition', '2021', str(path)], check=True)


def snake(name):
    name = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).lower()


names = re.findall(r'^LIVEKIT_SERVER_DECLARE_MODEL\((\w+)\)',
                   (root / 'include/livekit/server/model/models.h').read_text(encoding='utf-8'), re.M)
models = ['''use crate::{Error, Result};
use serde_json::Value;

// Store JSON privately: constructors and inspection never lend mutable internal protocol state.
macro_rules! model {
    ($name:ident) => {
        #[derive(Clone, Debug, PartialEq, Eq, Hash)]
        pub struct $name(String);
        impl Default for $name {
            fn default() -> Self { Self("{}".into()) }
        }
        impl $name {
            /// Preserve raw JSON for schema validation by the native SDK on invocation.
            pub fn from_json(json: impl Into<String>) -> Self { Self(json.into()) }
            pub fn from_value(value: Value) -> Result<Self> {
                if !value.is_object() { return Err(Error::InvalidArgument("Model JSON must be an object".into())); }
                Ok(Self(serde_json::to_string(&value)?))
            }
            pub fn json(&self) -> &str { &self.0 }
            pub fn to_value(&self) -> Result<Value> {
                let value: Value = serde_json::from_str(&self.0)?;
                if !value.is_object() { return Err(Error::InvalidArgument("Model JSON must be an object".into())); }
                Ok(value)
            }
        }
        impl std::fmt::Display for $name {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result { f.write_str(&self.0) }
        }
        impl serde::Serialize for $name {
            fn serialize<S: serde::Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
                self.to_value().map_err(serde::ser::Error::custom)?.serialize(serializer)
            }
        }
        impl<'de> serde::Deserialize<'de> for $name {
            fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
                let value = Value::deserialize(deserializer)?;
                Self::from_value(value).map_err(serde::de::Error::custom)
            }
        }
    };
}
''']
models += [f'model!({name});' for name in names]
models += ['\n#[cfg(test)]', 'mod tests {', '    use super::*;', '    #[test]',
           '    fn all_models_round_trip() {']
for name in names:
    models += [f'        let value = {name}::from_value(serde_json::json!({{"name": "中文\\0", "int64": "9007199254740993"}})).unwrap();',
               f'        assert_eq!(serde_json::from_str::<{name}>(&serde_json::to_string(&value).unwrap()).unwrap(), value);',
               f'        assert_eq!({name}::default().json(), "{{}}");']
models += ['    }', '}']
write('models.rs', models)

services = ['use crate::{models, LiveKitApi, Result};', '']
count = 0
for cls, header, accessor in [('RoomServiceClient', 'room_service_client', 'Room'),
                              ('EgressClient', 'egress_client', 'Egress'),
                              ('IngressClient', 'ingress_client', 'Ingress'),
                              ('SipClient', 'sip_client', 'Sip'),
                              ('AgentDispatchClient', 'agent_dispatch_client', 'AgentDispatch'),
                              ('ConnectorClient', 'connector_client', 'Connector')]:
    source = (root / f'include/livekit/server/{header}.h').read_text(encoding='utf-8')
    methods = re.findall(r'\[\[nodiscard\]\]\s+model::(\w+)\s+(\w+)\(const model::(\w+)& request\) const;', source)
    services += ['impl LiveKitApi {', f'    pub fn {snake(accessor)}(&self) -> {cls}<\'_> {{ {cls} {{ api: self }} }}', '}',
                 '#[derive(Clone, Copy, Debug)]', f'pub struct {cls}<\'a> {{ api: &\'a LiveKitApi }}',
                 f'impl {cls}<\'_> {{']
    for result, method, request in methods:
        services += [f'    pub fn {snake(method)}(&self, request: &models::{request}) -> Result<models::{result}> {{',
                     f'        Ok(models::{result}::from_json(self.api.call("{accessor}.{method}", request.json())?))', '    }']
        count += 1
    if accessor == 'AgentDispatch':
        services += ['    pub fn get_dispatch(&self, dispatch_id: &str, room: &str) -> Result<Option<models::AgentDispatch>> {',
                     '        self.api.get_dispatch(dispatch_id, room)', '    }']
    services += ['}', '']
write('services.rs', services)

grants = ['use serde::{Serialize, Deserialize};', '']
source = (root / 'include/livekit/server/access_token.h').read_text(encoding='utf-8')
for cls in ('VideoGrant', 'SipGrant', 'AgentGrant'):
    body = re.search(r'struct ' + cls + r' \{(.*?)\n\};', source, re.S)[1]
    grants += ['#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]', '#[serde(default)]', f'pub struct {cls} {{']
    for typ, name in re.findall(r'([\w:<>]+) (\w+)(?:\{\})?;', body):
        annotation = {'bool': 'bool', 'std::string': 'String', 'std::optional<bool>': 'Option<bool>',
                      'std::vector<std::string>': 'Vec<String>'}[typ]
        if typ == 'std::optional<bool>':
            grants += ['    #[serde(skip_serializing_if = "Option::is_none")]']
        grants += [f'    pub {name}: {annotation},']
    grants += ['}', '']
write('grants.rs', grants)
assert len(names) == 86 and count == 52
print(f'Generated {len(names)} Rust models and {count} service methods')
